param(
    [string]$Out = "",
    [string]$Version = ""
)
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$csc = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { throw '找不到 csc.exe' }

if (-not $Version) {
    $versionFile = Join-Path $root 'version.txt'
    if (Test-Path $versionFile) { $Version = (Get-Content $versionFile -Raw -Encoding UTF8).Trim() }
    if (-not $Version) { $Version = '0.0.0' }
}
$parts = @($Version.Split('.'))
while ($parts.Count -lt 3) { $parts += '0' }
$ver3 = ($parts[0..2] -join '.')
$ver4 = $ver3 + '.0'

if (-not $Out) { $Out = Join-Path $root 'dist\磁盘扩展包.exe' }
$outDir = Split-Path -Parent $Out
if ($outDir -and -not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }

$genDir = Join-Path $root 'src\generated'
if (-not (Test-Path $genDir)) { New-Item -ItemType Directory -Path $genDir -Force | Out-Null }
$genFile = Join-Path $genDir 'VersionInfo.g.cs'
$gen = @"
// <auto-generated>由 build-diskpack.ps1 生成，请勿手改</auto-generated>
using System.Reflection;
[assembly: AssemblyVersion("$ver4")]
[assembly: AssemblyFileVersion("$ver4")]
[assembly: AssemblyInformationalVersion("$ver3")]
namespace CCleaner { public static class VersionInfo { public const string Version = "$ver3"; } }
"@
[System.IO.File]::WriteAllText($genFile, $gen, (New-Object System.Text.UTF8Encoding($true)))

$files = @(
    (Join-Path $root 'src\Theme.cs'),
    (Join-Path $root 'src\Widgets.cs'),
    (Join-Path $root 'src\Models.cs'),
    (Join-Path $root 'src\Util.cs'),
    $genFile
) + @(Get-ChildItem (Join-Path $root 'diskpack\*.cs') | ForEach-Object { $_.FullName })

$cscArgs = @(
    '/nologo',
    '/target:winexe',
    '/platform:anycpu',
    '/optimize+',
    '/codepage:65001',
    "/out:$Out",
    "/win32icon:$root\app.ico",
    "/win32manifest:$root\app.manifest",
    '/r:System.dll',
    '/r:System.Core.dll',
    '/r:System.Drawing.dll',
    '/r:System.Windows.Forms.dll',
    '/r:System.Management.dll'
) + $files

& $csc $cscArgs
if ($LASTEXITCODE -ne 0) { throw "磁盘扩展包编译失败，退出码 $LASTEXITCODE" }

Get-Item $Out | Select-Object Name, Length, LastWriteTime
